import logging
import requests

from config import GROQ_API_KEY, GROQ_MODEL
from style_examples import STYLE_EXAMPLES

logger = logging.getLogger(__name__)

GROQ_URL = "https://api.groq.com/openai/v1/chat/completions"

# Хэштеги подбираются кодом (не ИИ) — надёжнее и без лишних токенов.
# Именно по ним люди находят канал через поиск Telegram.
CITY_HASHTAGS = {
    "астана": "#Астана", "алматы": "#Алматы", "шымкент": "#Шымкент",
    "караганда": "#Караганда", "павлодар": "#Павлодар",
}
TOPIC_HASHTAGS = {
    "закон": "#Закон", "поправк": "#Закон", "штраф": "#Штрафы",
    "льгот": "#Льготы", "выплат": "#Выплаты", "пенси": "#Пенсия",
    "экономик": "#Экономика", "спорт": "#Спорт",
}


def _build_hashtags(article):
    text = f"{article.get('title', '')} {article.get('summary', '')}".lower()
    tags = ["#Казахстан"]

    for keyword, tag in CITY_HASHTAGS.items():
        if keyword in text and tag not in tags:
            tags.append(tag)

    for keyword, tag in TOPIC_HASHTAGS.items():
        if keyword in text and tag not in tags:
            tags.append(tag)

    if article.get("is_legal") and "#Закон" not in tags:
        tags.append("#Закон")

    return " ".join(tags[:5])  # не больше 5, чтобы не выглядело спамом

# Системный промпт — задаёт логику комментирования, требования из ТЗ:
# - тон: как политик / как мотиватор / как журналист, всегда с лёгкой критикой
# - обязательный прогноз: плюсы и минусы новости для человека
# - если новость нейтральная/бытовая — короткая констатация + "будьте осторожны"
# - если трагедия/ЧП — аккуратный тон, без спекуляций, с предостережением
SYSTEM_PROMPT = """Ты пишешь комментарии к казахстанским новостям от лица автора канала.
Твоя роль сочетает три вещи одновременно:
1. Политик — видишь картину шире, даёшь взвешенную оценку происходящего.
2. Мотиватор — заряжаешь читателя действием, а не просто пересказываешь.
3. Журналист — точен с фактами, не выдумываешь то, чего нет в новости.

Стиль всегда слегка критикующий (не ноет, а указывает на суть проблемы или на то,
что могло бы быть сделано лучше), но не переходит в токсичность или оскорбления.

Обязательное правило: для любой новости, где это применимо, дай короткий прогноз —
что это значит для обычного человека: плюсы и минусы. Формат "Плюс: ... Минус: ...".

Если новость обычная/нейтральная (бытовая, без явной пользы или вреда) —
пиши короткую констатацию без раздувания, и обязательно вставь фразу-предостережение
по духу "будьте осторожны" — уместную к теме новости.

Если новость про трагедию/ЧП/погибших — тон аккуратный, без спекуляций и без черного юмора,
при уместности — предостережение читателям (как не попасть в похожую ситуацию).

Если новость полезная (закон, льгота, выплата, программа поддержки) — разбери,
какая конкретно выгода для человека и как её получить, и дай прогноз плюсы/минусы.

Пиши по-русски, разговорным языком, без канцелярита, короткими предложениями.
Комментарий должен быть 3-6 предложений — это пост в Telegram-канал, не статья.
Никогда не выдумывай факты, которых нет в присланном тексте новости.

В конце поста всегда добавляй короткий вопрос читателю по теме новости —
он должен звать высказаться в комментариях (например "А как думаете, кому
это на руку?" или "Вы бы так поступили?"), одна короткая фраза, не отдельный абзац.
"""

# Отдельные инструкции для новостей про законы/поправки —
# подход другой: объяснить простым языком, что именно изменилось.
LEGAL_INSTRUCTIONS = """
Это новость про новый закон, поправки или изменение в законодательстве Казахстана.

Пиши как юрист, который объясняет обычному человеку "на пальцах":
1. Какой закон/кодекс меняется (назови его).
2. Что конкретно исправили или добавили — простыми словами, без юридического жаргона.
3. Кого это касается (кто должен обратить внимание).
4. Прогноз: Плюс — что это даёт человеку. Минус — какие новые обязанности,
   риски или ограничения это создаёт.
Если из текста не ясно, что именно изменилось — честно скажи, что это принятый
документ, и посоветуй проверить детали по ссылке источника. Не придумывай содержание.
"""


def _style_block():
    if not STYLE_EXAMPLES:
        return ""
    examples = "\n\n".join(f"- {ex}" for ex in STYLE_EXAMPLES)
    return f"\n\nПримеры того, как обычно пишет автор канала (ориентируйся на тон и манеру речи):\n{examples}"


def generate_post(article):
    """
    article: {title, link, summary, source, is_legal}
    Возвращает готовый текст поста (с комментарием) или None при ошибке.
    """
    extra_instructions = LEGAL_INSTRUCTIONS if article.get("is_legal") else ""
    system_content = f"{SYSTEM_PROMPT}{extra_instructions}{_style_block()}"

    user_content = (
        f"Новость:\nЗаголовок: {article['title']}\n"
        f"Источник: {article['source']}\n"
        f"Текст: {article['summary'][:1500]}\n\n"
        f"Напиши готовый пост для Telegram-канала: короткий пересказ сути + твой комментарий "
        f"по правилам выше. Не добавляй хэштеги. Не пиши 'Заголовок:' или другие технические пометки."
    )

    try:
        resp = requests.post(
            GROQ_URL,
            headers={"Authorization": f"Bearer {GROQ_API_KEY}"},
            json={
                "model": GROQ_MODEL,
                "messages": [
                    {"role": "system", "content": system_content},
                    {"role": "user", "content": user_content},
                ],
                "temperature": 0.7,
            },
            timeout=30,
        )
        if resp.status_code != 200:
            logger.error(f"Ошибка генерации Groq ({resp.status_code}): {resp.text[:300]}")
            return None

        data = resp.json()
        text = data["choices"][0]["message"]["content"].strip()
        if not text:
            return None

        hashtags = _build_hashtags(article)
        return f"{text}\n\n{hashtags}"
    except Exception as e:
        logger.error(f"Ошибка генерации Groq: {e}")
        return None
